import assert from "node:assert/strict";
import { chromium } from "playwright";
const browser = await chromium.launch({ headless: true });
const base = process.env.BASE_URL ?? "http://127.0.0.1:3000";
const key = "ilws:classroom-presets:v1";
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await page.goto(`${base}/pack-builder`, { waitUntil: "networkidle" });
  await page.getByLabel("Pack title").fill("Science Class");
  await page.getByLabel("Words or phrases").fill("planet\ncomet\nstar");
  await page.getByLabel("Base seed").fill("assignment-1");
  await page.getByLabel("Puzzles").selectOption("20");
  await page.getByLabel("Paper size").selectOption("a4");
  await page.getByLabel("Download pages").selectOption("answers");
  assert.equal(await page.evaluate((key) => localStorage.getItem(key), key), null);
  await page.getByRole("button", { name: "Save preset on this device" }).click();
  await page.getByRole("button", { name: "Load Science Class", exact: true }).waitFor();
  await page.reload({ waitUntil: "networkidle" });
  await page.getByRole("button", { name: "Show saved presets" }).click();
  await page.getByRole("button", { name: "Load Science Class", exact: true }).click();
  assert.equal(await page.getByLabel("Words or phrases").inputValue(), "planet\ncomet\nstar");
  assert.equal(await page.getByLabel("Base seed").inputValue(), "assignment-1");
  assert.equal(await page.getByLabel("Puzzles").inputValue(), "20");
  assert.equal(await page.getByLabel("Paper size").inputValue(), "a4");
  assert.equal(await page.getByLabel("Download pages").inputValue(), "answers");
  await page.evaluate((key) => localStorage.setItem(key, "{corrupt"), key);
  await page.getByRole("button", { name: "Save preset on this device" }).click();
  assert.match(await page.locator("form").getByRole("alert").innerText(), /invalid|incompatible/);
  assert.equal(await page.evaluate((key) => localStorage.getItem(key), key), "{corrupt");
  await page.getByRole("button", { name: "Delete saved presets" }).click();
  assert.equal(await page.evaluate((key) => localStorage.getItem(key), key), null);
  assert.equal(await page.getByRole("button", { name: "Load Science Class", exact: true }).count(), 0);
  assert.equal(await page.getByLabel("Words or phrases").inputValue(), "planet\ncomet\nstar");
  await page.evaluate(() => Object.defineProperty(window, "localStorage", { configurable: true, get: () => { throw new Error("blocked"); } }));
  await page.getByRole("button", { name: "Show saved presets" }).click();
  assert.match(await page.locator("form").getByRole("alert").innerText(), /blocked/);
  assert.ok(await page.getByRole("button", { name: "Download PDF pack" }).isEnabled());
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  console.log("PASS explicit local preset save/reload,20 assignments/output choices,corrupt preservation,delete,blocked storage and mobile.");
} finally { await browser.close(); }
