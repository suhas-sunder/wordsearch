import assert from "node:assert/strict";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { chromium } from "playwright";
import AxeBuilder from "@axe-core/playwright";
import { getDocument } from "pdfjs-dist/legacy/build/pdf.mjs";
import { routeInventory } from "@/content/registry";
import { generatePuzzle } from "@/lib/puzzle/generate";
import { encodeShareState } from "@/lib/share-state/state";
import { measurePdfBytes } from "@/lib/pdf/measure-pdf";
import { readablePdfOptions } from "@/lib/pdf/browser-download";
import { defaultPuzzleOutputOptions } from "@/lib/puzzle/output-options";

const base = process.env.BASE_URL;
const output = process.env.READABLE_PDF_OUTPUT;
assert.ok(base && output, "Set BASE_URL and outside-Git READABLE_PDF_OUTPUT");
await mkdir(output, { recursive: true });
const source = routeInventory.find(record => record.canonicalPath === "/word-searches/science/biology-word-search");
assert.ok(source?.contentType === "puzzle");
const p = source.puzzle;
const dense = generatePuzzle({ title: p.puzzleTitle, wordsText: p.words.join("\n"), seed: p.seed, rows: p.rows, cols: p.columns, autoSize: false, directions: p.directions, allowOverlap: p.allowOverlap, alphabetPack: p.alphabetPack, difficulty: p.difficulty });
const clues = generatePuzzle({ title: "Readable clues", wordsText: "CAT | A small pet\nDOG | A friendly animal\nBIRD | An animal with feathers", seed: "readable-browser-clues", rows: 10, cols: 10, autoSize: false, directions: ["E"], wordBankMode: "clues" });
const report: object[] = [];
const browser = await chromium.launch();
try {
  for (const [width, paperSize, theme, puzzle] of [[390, "letter", "light", dense], [1280, "a4", "dark", dense], [390, "a4", "dark", clues], [1280, "letter", "light", clues]] as const) {
    const context = await browser.newContext({ viewport: { width, height: 1000 }, colorScheme: theme, acceptDownloads: true });
    await context.route("https://pagead2.googlesyndication.com/**", route => route.fulfill({ contentType: "application/javascript", body: "" }));
    const page = await context.newPage();
    const errors: string[] = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.goto(`${base}/word-search-generator?state=${encodeShareState(puzzle.request)}`, { waitUntil: "networkidle" });
    await page.locator(".builder-preview .puzzle-token").last().waitFor();
    const tokens = await page.locator(".builder-preview .puzzle-token").allTextContents();
    assert.deepEqual(tokens, puzzle.grid.flat());
    await page.locator(".preview-toolbar-actions").getByRole("button", { name: "Download PDF", exact: true }).click();
    const dialog = page.getByRole("dialog", { name: "Download PDF", exact: true });
    await dialog.getByRole("combobox", { name: "Paper size", exact: true }).selectOption(paperSize);
    await dialog.getByRole("combobox", { name: "Orientation", exact: true }).selectOption("landscape");
    await dialog.getByRole("combobox", { name: "Word bank", exact: true }).selectOption("beside");
    for (const name of ["Larger grid type", "Answer key page", "QR code", "Coordinates"]) await dialog.getByRole("checkbox", { name, exact: true }).check();
    const action = dialog.getByRole("button", { name: "Download readable PDF", exact: true });
    await action.scrollIntoViewIfNeeded();
    assert.deepEqual((await action.getAttribute("aria-describedby"))?.split(" "), ["alternate-pdf-description", "readable-pdf-description"]);
    assert.equal(await dialog.locator("#alternate-pdf-description").isVisible(), true);
    const layoutGaps = await dialog.locator(".measured-pdf-choice").evaluate(element => {
      const rectangles = Array.from(element.children, node => node.getBoundingClientRect());
      return rectangles.slice(1).map((rectangle, index) => rectangle.top - rectangles[index].bottom);
    });
    assert.ok(layoutGaps.every(gap => gap >= 0), `PDF layout descriptions/actions must not overlap: ${layoutGaps}`);
    const axe = await new AxeBuilder({ page }).include("dialog").analyze();
    assert.deepEqual(axe.violations.filter(item => ["serious", "critical"].includes(item.impact ?? "")), []);
    await page.screenshot({ path: resolve(output, `${width}-${paperSize}-${puzzle.request.wordBankMode ?? "words"}-choice.png`) });
    const pending = page.waitForEvent("download");
    await action.click();
    const download = await pending;
    assert.match(download.suggestedFilename(), /-readable\.pdf$/);
    const file = resolve(output, `${width}-${paperSize}-${puzzle.request.wordBankMode ?? "words"}.pdf`);
    await download.saveAs(file);
    const bytes = new Uint8Array(await readFile(file));
    const adjusted = readablePdfOptions({ ...defaultPuzzleOutputOptions, paperSize, includeAnswerKey: true });
    const student = await measurePdfBytes(bytes, puzzle, adjusted), answer = await measurePdfBytes(bytes, puzzle, adjusted, 2, true);
    assert.ok(student.grid.minFontPt >= 9 && answer.grid.minFontPt >= 9);
    assert.ok(student.wordBank.length === puzzle.placed.length && student.wordBank.every(word => word.fontPt === 9.5));
    assert.deepEqual(student.findings, []);
    assert.deepEqual(answer.findings, []);
    assert.ok(student.page.widthPt < student.page.heightPt);
    await dialog.waitFor({ state: "hidden" });
    await page.locator(".preview-toolbar-actions").getByRole("button", { name: "Download PDF", exact: true }).click();
    assert.equal(await dialog.getByRole("combobox", { name: "Orientation", exact: true }).inputValue(), "landscape");
    assert.equal(await dialog.getByRole("combobox", { name: "Word bank", exact: true }).inputValue(), "beside");
    for (const name of ["Larger grid type", "Answer key page", "QR code", "Coordinates"]) assert.equal(await dialog.getByRole("checkbox", { name, exact: true }).isChecked(), true);
    await page.keyboard.press("Escape");
    assert.deepEqual(await page.locator(".builder-preview .puzzle-token").allTextContents(), tokens);
    assert.deepEqual(errors, []);
    report.push({ width, paperSize, theme, wordBankMode: puzzle.request.wordBankMode, gridMinimum: student.grid.minFontPt, bankSize: 9.5, ordinaryChoicesPreserved: true });
    await context.close();
  }
  const context = await browser.newContext({ acceptDownloads: true });
  await context.route("https://pagead2.googlesyndication.com/**", route => route.fulfill({ contentType: "application/javascript", body: "" }));
  const page = await context.newPage();
  const crowded = generatePuzzle({ title: "Readable fit recovery", wordsText: "CAT\nDOG", seed: "readable-browser-error", rows: 40, cols: 40, autoSize: false, directions: ["E"] });
  await page.goto(`${base}/word-search-generator?state=${encodeShareState(crowded.request)}`, { waitUntil: "networkidle" });
  const tokens = await page.locator(".builder-preview .puzzle-token").allTextContents();
  await page.locator(".preview-toolbar-actions").getByRole("button", { name: "Download PDF", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Download PDF", exact: true });
  let downloads = 0;
  page.on("download", () => downloads++);
  await dialog.getByRole("button", { name: "Download readable PDF", exact: true }).click();
  await dialog.getByRole("alert").filter({ hasText: "minimum 9-point" }).waitFor();
  assert.equal(downloads, 0);
  assert.deepEqual(await page.locator(".builder-preview .puzzle-token").allTextContents(), tokens);
  const pending = page.waitForEvent("download");
  await dialog.getByRole("button", { name: "Download PDF", exact: true }).click();
  const ordinary = await pending;
  assert.doesNotMatch(ordinary.suggestedFilename(), /-readable\.pdf$/);
  await ordinary.saveAs(resolve(output, "explicit-legacy-after-readable-error.pdf"));
  const task = getDocument({ data: new Uint8Array(await readFile((await ordinary.path())!)), useSystemFonts: true });
  try {
    const pdf = await task.promise;
    const text = (await (await pdf.getPage(1)).getTextContent()).items.map(item => "str" in item ? item.str : "");
    assert.deepEqual(text.filter(item => /^[A-Z]$/.test(item)), crowded.grid.flat());
  } finally { await task.destroy(); }
  report.push({ crowdedReadableRefused: true, noSilentFallback: true, explicitLegacyRetry: true });
  const morse = generatePuzzle({ title: "Readable alphabet limit", wordsText: "CAT\nDOG", seed: "readable-morse-browser", rows: 8, cols: 8, autoSize: false, directions: ["E"], alphabetPack: "morse" });
  await page.goto(`${base}/word-search-generator?state=${encodeShareState(morse.request)}`, { waitUntil: "networkidle" });
  await page.locator(".preview-toolbar-actions").getByRole("button", { name: "Download PDF", exact: true }).click();
  const priorDownloads = downloads;
  await dialog.getByRole("button", { name: "Download readable PDF", exact: true }).click();
  await dialog.getByRole("alert").filter({ hasText: "one character per grid cell" }).waitFor();
  assert.equal(downloads, priorDownloads);
  report.push({ unsupportedCellsExplained: true, noUnsupportedFile: true });
  await context.close();
} finally {
  await browser.close();
  await writeFile(resolve(output, "report.json"), JSON.stringify({ base, cases: report }, null, 2));
}
console.log("PASS readable PDFs: exact student/teacher grids, measured words/clues, preserved choices, no silent shrinking and explicit ordinary retry.");
