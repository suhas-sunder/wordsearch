import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { chromium, type Page } from "playwright";
import AxeBuilder from "@axe-core/playwright";

declare global {
  interface Window { __holdBuilderDebounce: boolean; __releaseBuilderDebounce(): void; }
}
const base = process.env.BASE_URL;
const output = process.env.BUILDER_ERROR_OUTPUT;
assert.ok(base && output, "Set BASE_URL and outside-repository BUILDER_ERROR_OUTPUT");
await mkdir(output, { recursive: true });
const words = "CAT | A small, purring pet | feline\nPLANET | A world orbiting a star\nOX | A working animal";
const request = { title: "F1 clue worksheet", wordsText: words, seed: "f1-clue-visual", rows: 10, cols: 10, autoSize: false, directions: ["E"], wordBankMode: "clues", wordBankOrder: "input" };
const state = Buffer.from(JSON.stringify(request)).toString("base64url");
// Exact grid observed independently on C2 before the UI-only correction, at
// both mobile and desktop. This is not generated by the implementation tested.
const expectedGridSha = "f2ca0daa4b38e5ac6cf6edc6908c8e647e1442afd9b4af4ccee2d100eba2d3f5";
const report: object[] = [];
async function metrics(page: Page) {
  return page.locator(".builder-preview").evaluate((node) => {
    const css = getComputedStyle(node), alert = node.querySelector<HTMLElement>('[role="alert"]');
    const alertCss = alert ? getComputedStyle(alert) : null;
    return { busy: node.getAttribute("aria-busy"), height: node.getBoundingClientRect().height, minHeight: parseFloat(css.minHeight) || 0,
      naturalErrorHeight: alert && alertCss ? alert.getBoundingClientRect().height + parseFloat(alertCss.marginTop) + parseFloat(alertCss.marginBottom) + parseFloat(css.paddingTop) + parseFloat(css.paddingBottom) + parseFloat(css.borderTopWidth) + parseFloat(css.borderBottomWidth) : null,
      alerts: node.querySelectorAll('[role="alert"]').length, gridCells: node.querySelectorAll(".puzzle-token").length, outputButtons: node.querySelectorAll(".export-row button").length };
  });
}
const browser = await chromium.launch();
try {
  for (const width of [390, 1280]) {
    const context = await browser.newContext({ viewport: { width, height: 1000 } });
    try {
      await context.route("https://pagead2.googlesyndication.com/**", (route) => route.fulfill({ contentType: "application/javascript", body: "" }));
      await context.addInitScript(`(() => {
        const set = window.setTimeout.bind(window), clear = window.clearTimeout.bind(window);
        const held = new Map();
        window.__holdBuilderDebounce = false;
        // Only the existing builder debounce is held; canceled tasks stay canceled.
        window.setTimeout = (callback, delay, ...args) => {
          if (window.__holdBuilderDebounce && delay === 220 && typeof callback === "function") {
            const id = set(() => {}, 60000);
            held.set(id, () => callback(...args)); return id;
          }
          return set(callback, delay, ...args);
        };
        window.clearTimeout = (id) => { held.delete(id); clear(id); };
        window.__releaseBuilderDebounce = () => {
          window.__holdBuilderDebounce = false;
          const pending = [...held]; held.clear();
          for (const [id, task] of pending) { clear(id); task(); }
        };
      })();`);
      const page = await context.newPage();
      const errors: string[] = []; page.on("pageerror", (error) => errors.push(error.message));
      await page.goto(`${base}/word-search-generator?state=${state}`, { waitUntil: "networkidle" });
      await page.locator(".builder-preview .print-clue-bank span").first().waitFor();
      await page.waitForFunction(() => [...document.querySelectorAll<HTMLElement>(".print-fit-status")].every((node) => node.dataset.fitState === "ready"));
      const gridHash = async () => createHash("sha256").update(JSON.stringify(await page.locator(".preview-paper .puzzle-token").allTextContents())).digest("hex");
      assert.equal(await gridHash(), expectedGridSha);
      const ready = await metrics(page); assert.equal(ready.busy, "false");
      await page.getByText("Advanced print and fill controls", { exact: true }).click();
      await page.evaluate(() => { window.__holdBuilderDebounce = true; });
      const title = page.getByRole("textbox", { name: "Puzzle title", exact: true });
      await title.fill("Pending title");
      await page.locator('.builder-preview[aria-busy="true"]').waitFor().catch(async (error) => { await writeFile(`${output}/pending-failure-${width}.json`, JSON.stringify({ url: page.url(), errors, body: await page.locator("body").innerText() }, null, 2)); throw error; });
      const pending = await metrics(page);
      assert.ok(pending.minHeight > 0, "actual pending work retains its previous preview reservation");
      assert.ok(pending.height >= pending.minHeight - 1);
      assert.equal(pending.alerts, 0); assert.equal(pending.gridCells, 0); assert.equal(pending.outputButtons, 0);
      const input = page.getByRole("textbox", { name: "Words and clues", exact: true });
      await input.focus(); await page.keyboard.press("Control+A");
      await page.keyboard.insertText("CAT |\nPLANET | A world orbiting a star\nOX | A working animal");
      await page.locator(".builder-preview [role=alert]").waitFor();
      await page.waitForFunction(() => document.querySelector(".builder-preview")?.getAttribute("aria-busy") === "false");
      const invalid = await metrics(page);
      assert.equal(invalid.minHeight, 0);
      assert.ok(invalid.height < pending.height / 2, "settled error does not keep the old worksheet-sized blank region");
      assert.ok(invalid.naturalErrorHeight !== null && Math.abs(invalid.height - invalid.naturalErrorHeight) <= 2, "error height follows actual message, margins and padding");
      assert.equal(invalid.gridCells, 0); assert.equal(invalid.outputButtons, 0);
      assert.equal(await input.evaluate((node) => node === document.activeElement), true, "keyboard input retains focus");
      assert.match(await page.locator(".builder-preview [role=alert]").textContent() ?? "", /Clue mode needs.*Correct the settings above/);
      const axe = await new AxeBuilder({ page }).include(".builder-surface").analyze();
      assert.deepEqual(axe.violations.filter((issue) => ["serious", "critical"].includes(issue.impact ?? "")), []);
      await page.locator(".builder-preview").screenshot({ path: `${output}/error-${width}.png` });
      await title.fill(request.title); await input.fill(words);
      await page.locator('.builder-preview[aria-busy="true"]').waitFor().catch(async (error) => { await writeFile(`${output}/pending-failure-${width}.json`, JSON.stringify({ url: page.url(), errors, body: await page.locator("body").innerText() }, null, 2)); throw error; });
      const recovering = await metrics(page);
      assert.ok(recovering.minHeight > 0); assert.equal(recovering.alerts, 0); assert.equal(recovering.outputButtons, 0);
      await page.evaluate(() => window.__releaseBuilderDebounce());
      await page.locator(".builder-preview .print-clue-bank span").first().waitFor();
      await page.waitForFunction(() => document.querySelector(".builder-preview")?.getAttribute("aria-busy") === "false" && [...document.querySelectorAll<HTMLElement>(".print-fit-status")].every((node) => node.dataset.fitState === "ready"));
      const recovered = await metrics(page);
      assert.equal(recovered.minHeight, 0); assert.equal(recovered.alerts, 0);
      assert.ok(recovered.outputButtons > 0); assert.equal(await gridHash(), expectedGridSha);
      assert.deepEqual(await page.locator(".builder-preview .print-clue-bank span").allTextContents(), ["1. A small, purring pet | feline", "2. A world orbiting a star", "3. A working animal"]);
      assert.deepEqual(errors, []);
      report.push({ width, expectedGridSha, ready, pending, invalid, recovering, recovered });
    } finally { await context.close(); }
  }
  await writeFile(`${output}/result.json`, JSON.stringify({ base, scope: "Actual browser pending/error/recovery with only debounce held; normal ad correctness mock; not manual screen-reader or performance approval", report }, null, 2));
  console.log("PASS mobile/desktop busy, reservation, settled error natural height, keyboard/axe, no-fallback outputs and exact generation recovery");
} finally { await browser.close(); }
